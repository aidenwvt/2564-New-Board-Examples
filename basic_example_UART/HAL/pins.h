/*
 * pins.h
 *
 * Port, pin, IOMUX, and pin function names for every GPIO pin on the MSPM0G3507.
 *
 * On this chip, setting up a pin and using a pin go through two different blocks:
 *   1. Set it up (GPIO or a peripheral, pull-up/pull-down, input enable): the IOMUX block,
 *      which has one Pin Control Management register (PINCM) per physical pin -> Pxx_IOMUX
 *   2. Use it (read, set, clear, output enable): the GPIO port -> Pxx_PORT and Pxx_PIN
 * PINCM numbers follow the physical pin order, not the port, so there is no formula from
 * a port and pin to its PINCM. This file does the lookup once so code can use the port
 * and pin printed on the LaunchPad.
 *
 * Each pin can also be handed to a peripheral instead of GPIO. Pxx_<FUNCTION> names the
 * functions that pin can carry, for DL_GPIO_initPeripheralInputFunction/OutputFunction.
 * Only the functions listed under a pin are available on that pin.
 *
 * Example, PB21 as an input with the internal pull-up:
 *   DL_GPIO_initDigitalInputFeatures(PB21_IOMUX, DL_GPIO_INVERSION_DISABLE,
 *       DL_GPIO_RESISTOR_PULL_UP, DL_GPIO_HYSTERESIS_DISABLE, DL_GPIO_WAKEUP_DISABLE);
 *   if (DL_GPIO_readPins(PB21_PORT, PB21_PIN) == 0) { ... }
 *
 * Example, PA10 as UART0 transmit:
 *   DL_GPIO_initPeripheralOutputFunction(PA10_IOMUX, PA10_UART0_TX);
 *
 * Generated from the MSPM0 SDK 2.11.00.07 header ti/devices/msp/m0p/mspm0g350x.h
 * (IOMUX_PINCMxx_PF_... definitions).
 */

